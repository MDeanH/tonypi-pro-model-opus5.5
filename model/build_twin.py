"""Build the TonyPi Pro twin: vendor MJCF (topology, meshes, geoms, sites, sensors) + model/ledger.csv (every number).

Usage: .venv/bin/python -I model/build_twin.py [--out build/tonypi_pro_as_is.xml]

Spine 2: each frame offset, axis, joint range, torque limit, joint damping/friction/armature, servo gain, mass,
centre of mass and inertia in the output comes from an ACTIVE ledger row. A required value with no active row stops
the build: nothing is silently defaulted. MuJoCo's own mass-from-geometry inference is switched off (the vendor's
per-geom masses are already folded into the ledger's link inertials), and so is inertia balancing, so the compiled
numbers are the ledger's. What the ledger lacks (servo velocity limits, unless a Hiwonder figure is entered) is
listed in the report, never filled. Geometry (mesh shapes, collision primitives) is the vendor's, sha-pinned in
vendor/tonypi/SHA256SUMS.

The output is FIXED-BASE: the torso is welded where the vendor's `home` keyframe puts its free root. The vendor's
three free-root keyframes are dropped because their qpos no longer fits. sim/build_contact_scene.py derives the
floating-base, floor-contact scene from this file.
"""
import argparse
import math
import os
import re
import sys

import mujoco

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "tools"))
import inspect_mjcf  # noqa: E402
import seed_ledger as sl  # noqa: E402

VENDOR = sl.VENDOR
DEFAULT_OUT = os.path.join(REPO, "build", "tonypi_pro_as_is.xml")
INERTIA_KEYS = sl.INERTIA_KEYS
DYNAMICS = ("damping", "frictionloss", "armature")
VENDOR_HEADER = ("<!-- GENERATED by tools/gen_mjcf.py from joints.json,\n"
                 "       link_inventory.json and inertia.json. Do not hand-edit. -->")
OUR_HEADER = ("<!-- GENERATED by model/build_twin.py from vendor/tonypi/model/robot.xml (pab47/TonyPi 97807f5)\n"
              "       + model/ledger.csv. Do not hand-edit: change the ledger and rebuild. -->")


class Ledger:
    """Active ledger values; records every param the build reads, so the report can say where each came from."""

    def __init__(self, path=sl.LEDGER):
        rows = sl.read(path)
        if not rows:
            raise SystemExit(f"no ledger at {path}; run tools/seed_ledger.py first")
        problems = sl.ledger_problems(rows)
        if problems:
            raise SystemExit("ledger has problems; fix them first:\n  " + "\n  ".join(problems[:10]))
        self.active = {r["param"]: r for r in rows if r["status"] == "active"}
        self.missing = {r["param"] for r in rows if r["status"] == "missing"}
        self.used = {}

    def has(self, param):
        return param in self.active

    def need(self, param):
        if param not in self.active:
            raise SystemExit(f"build stopped: no active ledger value for {param}")
        r = self.active[param]
        self.used[param] = r
        return float(r["value"])

    def maybe(self, param):
        return self.need(param) if param in self.active else None


def rpy_to_quat(r, p, y):
    cr, sr, cp, sp, cy, sy = (math.cos(r / 2), math.sin(r / 2), math.cos(p / 2), math.sin(p / 2),
                              math.cos(y / 2), math.sin(y / 2))
    return [cr * cp * cy + sr * sp * sy, sr * cp * cy - cr * sp * sy, cr * sp * cy + sr * cp * sy,
            cr * cp * sy - sr * sp * cy]


def posix(path):
    return path.replace(os.sep, "/")


def build(ledger_path=sl.LEDGER, out=DEFAULT_OUT):
    out = os.path.abspath(out)
    led = Ledger(ledger_path)
    vendor = inspect_mjcf.Vendor(VENDOR)
    joint_of = {b["name"]: b["joint"] for b in vendor.bodies}
    spec = mujoco.MjSpec.from_file(VENDOR)
    if spec.meshdir:
        raise SystemExit("build stopped: the vendor file sets a meshdir; extend build_twin")
    spec.modelname = "tonypi_pro_as_is"
    spec.compiler.balanceinertia = False
    spec.compiler.inertiafromgeom = mujoco.mjtInertiaFromGeom.mjINERTIAFROMGEOM_FALSE
    report = dict(gaps=[], unenforced=[], scene=[], dropped=[], upstream=[])

    root = [j for j in spec.joints if j.type == mujoco.mjtJoint.mjJNT_FREE]
    if [j.name for j in root] != ["root"]:
        raise SystemExit(f"build stopped: expected one free joint named root, found {[j.name for j in root]}")
    spec.delete(root[0])
    for k in list(spec.keys):
        report["dropped"].append(k.name)
        spec.delete(k)

    for b in spec.bodies:
        name = b.name
        if name == "world":
            continue
        j = joint_of.get(name)
        if j:
            b.pos = [led.need(f"joint.{j}.origin.{k}") for k in "xyz"]
            b.quat = rpy_to_quat(*(led.need(f"joint.{j}.origin.{k}") for k in ("roll", "pitch", "yaw")))
        else:
            b.pos = [led.need(f"scene.home.root.{k}") for k in "xyz"]
            q = [led.need(f"scene.home.root.{k}") for k in ("qw", "qx", "qy", "qz")]
            n = math.sqrt(sum(x * x for x in q))
            b.quat = [x / n for x in q]
            report["scene"].append(f"{name} welded to the world at {[round(float(x), 6) for x in b.pos]} m, quat "
                                   f"{[round(float(x), 6) for x in b.quat]} (vendor `home` keyframe free-root pose)")
        # Every vendor link has real parts (servo cases, brackets): a link with no mass row stops the build.
        b.explicitinertial = True
        b.mass = led.need(f"link.{name}.mass")
        b.ipos = [led.need(f"link.{name}.com.{k}") for k in "xyz"]
        b.inertia, b.iquat = [0, 0, 0], [1, 0, 0, 0]  # clear the principal diagonal so fullinertia applies
        b.fullinertia = [led.need(f"link.{name}.inertia.{k}") for k in INERTIA_KEYS]

    for jn in spec.joints:
        jname = jn.name
        jn.axis = [led.need(f"joint.{jname}.axis.{k}") for k in "xyz"]
        jn.range = [led.need(f"joint.{jname}.limit.lower"), led.need(f"joint.{jname}.limit.upper")]
        jn.limited = mujoco.mjtLimited.mjLIMITED_TRUE
        for k in DYNAMICS:
            p = f"joint.{jname}.dynamics.{k}"
            # 0 only for an explicit `missing` row; an absent row (e.g. a mistyped replacement) stops the build.
            v = led.maybe(p) if p in led.missing else led.need(p)
            val = v if v is not None else 0.0
            # MuJoCo 3.17: damping is a 3-vector (linear term first); frictionloss/armature are scalars.
            setattr(jn, k, [val, 0.0, 0.0] if k == "damping" else val)
            if v is None:
                report["gaps"].append(f"joint.{jname}.dynamics.{k}")
        vel = led.maybe(f"joint.{jname}.limit.velocity")
        report["unenforced"].append(f"joint.{jname}.limit.velocity = {vel if vel is not None else 'MISSING'} rad/s "
                                    f"(MuJoCo has no joint velocity limit; a controller must enforce it)")

    for a in spec.actuators:
        if a.gaintype != mujoco.mjtGain.mjGAIN_FIXED or a.biastype != mujoco.mjtBias.mjBIAS_AFFINE:
            raise SystemExit(f"build stopped: actuator {a.name} is not a position servo")
        kp = led.need(f"actuator.{a.name}.kp")
        zeta = led.need(f"actuator.{a.name}.dampratio")
        gain, bias = list(a.gainprm), list(a.biasprm)
        gain[0] = kp
        bias[0], bias[1], bias[2] = 0.0, -kp, zeta  # MuJoCo stores dampratio as a positive biasprm[2]
        a.gainprm, a.biasprm = gain, bias
        e = led.need(f"joint.{a.target}.limit.effort")
        a.forcerange, a.forcelimited = [-e, e], mujoco.mjtLimited.mjLIMITED_TRUE
        a.ctrlrange = [led.need(f"actuator.{a.name}.ctrlrange.lower"), led.need(f"actuator.{a.name}.ctrlrange.upper")]
        a.ctrllimited = mujoco.mjtLimited.mjLIMITED_TRUE

    unused = sorted(p for p in led.active if p not in led.used and not p.startswith(("robot.", "servo.")))
    if unused:
        raise SystemExit("build stopped: active ledger rows the build does not read (check the spelling): "
                         + ", ".join(unused[:10]))
    for p, r in led.used.items():
        if r["source"] == "vendor" and ("ESTIMATE" in r["note"] or "no basis" in r["note"] or "FIX" in r["note"]
                                        or "simulation" in r["note"]):
            report["upstream"].append(p)

    os.makedirs(os.path.dirname(out), exist_ok=True)
    # Compile from the output folder with a relative meshdir, so the written XML resolves from its own folder and no
    # absolute path (which MuJoCo's writer may escape) is ever string-matched.
    reldir = posix(os.path.relpath(os.path.dirname(VENDOR), os.path.dirname(out)))
    spec.meshdir, spec.modelfiledir = reldir, ""
    cwd = os.getcwd()
    os.chdir(os.path.dirname(out))
    try:
        model = spec.compile()  # raises on any inconsistency
        text = spec.to_xml()
    finally:
        os.chdir(cwd)
    if text.count(f'meshdir="{reldir}"') != 1:
        raise SystemExit("build stopped: unexpected meshdir in the written XML")
    # MjSpec carries the vendor's leading comment into the output; it names the vendor's generator, not ours.
    if text.count(VENDOR_HEADER) != 1:
        raise SystemExit("build stopped: the vendor header comment changed; update VENDOR_HEADER")
    text = text.replace(VENDOR_HEADER, OUR_HEADER)
    text = restore_dampratio(text, led, [a.name for a in spec.actuators])
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    # The XML is rounded by MuJoCo's writer (~6 significant figures); the binary model keeps every number exactly.
    mujoco.mj_saveModel(model, os.path.splitext(out)[0] + ".mjb", None)
    write_report(out, led, report, model, vendor)
    return model, led, report


def restore_dampratio(text, led, names):
    """Put each servo's ledger dampratio back into the XML.

    MuJoCo converts a position servo's dampratio into a damping gain kv at compile time, using the joint inertia
    of THAT model, and the XML writer then saves the converted kv. Saved as kv, a fixed-base value would be
    carried into every derived scene (the floating-base one needs a different kv for the same dampratio, ~9% on
    the hip-roll servos). Writing the dampratio back (a positive biasprm[2]) makes every scene that loads this
    file derive kv for its own base, exactly as the vendor's own <position dampratio=...> does.
    """
    for name in names:
        pat = re.compile(r'(<general name="' + re.escape(name) + r'" [^>]*?biasprm=")([^"]*)(")')
        found = pat.findall(text)
        if len(found) != 1:
            raise SystemExit(f"build stopped: expected one biasprm on actuator {name}, found {len(found)}")
        bias = found[0][1].split()
        kp = led.active[f"actuator.{name}.kp"]["value"]
        if len(bias) != 3 or float(bias[0]) != 0.0 or not math.isclose(float(bias[1]), -float(kp), rel_tol=1e-5) or float(bias[2]) >= 0:
            raise SystemExit(f"build stopped: unexpected biasprm {found[0][1]!r} on actuator {name}")
        zeta = led.active[f"actuator.{name}.dampratio"]["value"]
        text = pat.sub(lambda m: f"{m.group(1)}{bias[0]} {bias[1]} {zeta}{m.group(3)}", text)
    return text


def cross_checks(led, total_mass):
    """Compare vendor servo numbers and the model mass with Hiwonder's published figures (docs rows)."""
    act = led.active
    out = []

    def rel(a, b):
        return f"{100 * (a - b) / b:+.2f}%"
    pairs = [("LX-824HV", "r_knee"), ("LFD-01M", "head_pan")]
    for servo, joint in pairs:
        stall = act.get(f"servo.{servo}.stall_torque")
        speed = act.get(f"servo.{servo}.no_load_speed")
        effort = act.get(f"joint.{joint}.limit.effort")
        damping = act.get(f"joint.{joint}.dynamics.damping")
        if not (stall and speed and effort and damping):
            out.append(f"- {servo}: no Hiwonder figures in the ledger")
            continue
        s, w, e, c = (float(x["value"]) for x in (stall, speed, effort, damping))
        out.append(f"- {servo} torque cap: vendor {e:g} N*m vs Hiwonder stall {s:.4f} N*m ({rel(e, s)})")
        out.append(f"- {servo} damping (stall / no-load speed): vendor {c:g} vs Hiwonder-derived {s / w:.4f} N*m*s/rad "
                   f"({rel(c, s / w)})")
    label = act.get("robot.mass_label")
    if label:
        out.append(f"- Total mass: model {total_mass:.6f} kg vs Hiwonder 'about {float(label['value']) * 1000:.0f} g' "
                   f"({rel(total_mass, float(label['value']))}); the label may exclude the Pro hands")
    return out


def mass_breakdown(vendor):
    """Vendor per-part masses (geoms with an explicit mass), grouped by kind, for the report."""
    kinds = {}
    for b in vendor.bodies:
        for g in b["geoms"]:
            m = float(g.get("mass", 0) or 0)
            if m <= 0:
                continue
            name = g["name"]
            kind = ("LX-824HV servo case" if name.endswith("_servo") and not name.startswith("head")
                    else "LFD-01M servo case" if name.startswith("head") and name.endswith("_servo")
                    else name.split("torso_", 1)[1].replace("_", " ") if name.startswith("torso_")
                    else name.rsplit("_", 1)[-1])
            n, tot = kinds.get(kind, (0, 0.0))
            kinds[kind] = (n + 1, tot + m)
    return kinds


def write_report(out, led, report, model, vendor):
    by_source = {}
    for r in led.used.values():
        by_source[r["source"]] = by_source.get(r["source"], 0) + 1
    estimates = sorted(p for p, r in led.used.items() if r["source"] == "estimate")
    total = float(model.body_mass.sum())
    label = led.active.get("robot.mass_label")
    label_txt = (f"Hiwonder lists {label['value']} {label['unit']}" if label
                 else "no Hiwonder weight in the ledger")
    upstream_est = sorted(p for p in report["upstream"] if "ESTIMATE" in led.used[p]["note"])
    upstream_tune = sorted(p for p in report["upstream"] if p not in upstream_est and
                           ("FIX" in led.used[p]["note"] or "simulation" in led.used[p]["note"]))
    upstream_nobasis = sorted(p for p in report["upstream"] if "no basis" in led.used[p]["note"])
    lines = [f"# Twin build report — {os.path.basename(out)}", "",
             "Generated by `model/build_twin.py` from the vendor MJCF (structure, meshes) + `model/ledger.csv` (numbers).",
             "**Status: builds and simulates. NOT validated against a physical TonyPi Pro** (no unit measured, no "
             "telemetry replayed).", "",
             "Files: `.mjb` = exact (every number equals the ledger); `.xml` = readable, MuJoCo's writer rounds to ~6 "
             "significant figures.", "",
             f"- Bodies {model.nbody}, joints {model.njnt} (DOF {model.nv}), actuators {model.nu}, sensors "
             f"{model.nsensor}, total mass {total:.6f} kg ({label_txt})",
             f"- Ledger values used: {len(led.used)} — by source: " + ", ".join(f"{k} {v}" for k, v in sorted(by_source.items())),
             f"- Base: fixed (torso welded); vendor free-root keyframes dropped: {', '.join(report['dropped']) or 'none'}",
             "",
             f"## Our estimates used ({len(estimates)})", ""]
    lines += [f"- `{p}` = {led.used[p]['value']} {led.used[p]['unit']}" for p in estimates] or ["- none"]
    lines += ["", "## Vendor values the vendor itself qualifies", "",
              "The pinned upstream model is a third-party reconstruction. Its own comments label these numbers; the "
              "ledger's `note` column carries each label.", "",
              f"- Labelled ESTIMATE upstream: {len(upstream_est)} (" +
              ", ".join(sorted({p.rsplit('.', 1)[-1] for p in upstream_est})) + ")",
              f"- Simulation tuning, not hardware properties: {len(upstream_tune)} (servo kp and dampratio; kp 64 on the "
              f"four roll joints is upstream's walking-clearance fix)",
              f"- No basis given upstream: {len(upstream_nobasis)} (joint frictionloss, head-servo armature)", ""]
    lines += ["## Hiwonder cross-checks (vendor numbers against Hiwonder datasheets; not checks of a physical unit)", ""]
    lines += cross_checks(led, total)
    lines += ["", f"## Gaps — set to 0 in the model because nothing is known ({len(report['gaps'])})", ""]
    lines += [f"- {g}" for g in report["gaps"]] or ["- none: every joint has vendor damping, frictionloss and armature "
                                                    "(see the qualifications above)"]
    n_missing_vel = sum("MISSING" in u for u in report["unenforced"])
    lines += ["", "## Not enforced by MuJoCo", "",
              f"Joint velocity limits are not part of MuJoCo's joint model. {n_missing_vel} of "
              f"{len(report['unenforced'])} joints have no velocity figure in the ledger.", ""]
    missing_first = sorted(report["unenforced"], key=lambda u: "MISSING" not in u)
    lines += [f"- {u}" for u in missing_first[:max(3, n_missing_vel)]] + \
             [f"- … {len(report['unenforced']) - max(3, n_missing_vel)} more joints, same note"]
    lines += ["", "## Mass breakdown (vendor per-part masses, folded into the ledger's link inertials)", "",
              "| Part kind | Count | Mass (kg) |", "| --- | ---: | ---: |"]
    for kind, (n, m) in sorted(mass_breakdown(vendor).items(), key=lambda kv: -kv[1][1]):
        lines.append(f"| {kind} | {n} | {m:.6f} |")
    lines += ["", "## Scene", ""] + [f"- {s}" for s in report["scene"]] + [
        "- No floor and no contact with the world: use build/tonypi_pro_contact_candidate.xml for floor contact.",
        "- Vendor collision primitives, self-collision guards, contact exclusions, the foot-to-foot contact pair, "
        "the IMU site and all 45 sensors are kept unchanged."]
    with open(os.path.splitext(out)[0] + ".report.md", "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=DEFAULT_OUT)
    a = ap.parse_args(argv)
    model, led, report = build(out=os.path.abspath(a.out))
    print(f"built {posix(os.path.relpath(os.path.abspath(a.out), REPO))}: DOF {model.nv}, actuators {model.nu}, "
          f"total mass {float(model.body_mass.sum()):.6f} kg, {len(led.used)} ledger values used, "
          f"{len(report['gaps'])} gaps, {sum('MISSING' in u for u in report['unenforced'])} joints without a "
          f"velocity limit")
    return 0


if __name__ == "__main__":
    sys.exit(main())
