"""Generate the synthetic demonstration action groups in data/action-groups/ (and their MANIFEST.json).

Usage:
  .venv/bin/python -I tools/make_demo_action.py           write the .d6a files and MANIFEST.json (refuses to overwrite)
  .venv/bin/python -I tools/make_demo_action.py --check   verify the checked-in files equal the generator output

These are NOT recordings from a robot. Each demo is a few joint-angle keyframes written here by hand, converted to
bus-servo pulses with the REFERENCE calibration (the upstream author's robot, model/servo_map.csv ref_* columns) and
stored in Hiwonder's .d6a layout (SQLite table ActionGroup: [Index], Time in ms, Servo1-Servo16 pulses). They exist
to exercise the parser and playback; played with `--calibration reference` they reproduce the angles below to
within the 0.24-degree pulse resolution. On a physical robot they would only mean these angles if its servo zeros
matched the reference robot's.
"""
import argparse
import hashlib
import json
import os
import sqlite3
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "tools"))
import servo_map  # noqa: E402

DATA = os.path.join(REPO, "data", "action-groups")
MANIFEST = os.path.join(DATA, "MANIFEST.json")
BODY_IDS = list(range(1, 17))
SQUAT = {"hip_pitch": -0.35, "knee": 0.70, "ankle_pitch": -0.35}  # thigh forward, shin back, sole level
DEMOS = {
    "demo_wave_left.d6a": {
        "description": "raise the left arm sideways, wave the forearm twice, return to the home pose",
        "frames": [
            (700, {"l_shoulder_roll": 2.3}),
            (300, {"l_shoulder_roll": 2.3, "l_elbow": 0.5}),
            (300, {"l_shoulder_roll": 2.3, "l_elbow": -0.5}),
            (300, {"l_shoulder_roll": 2.3, "l_elbow": 0.5}),
            (300, {"l_shoulder_roll": 2.3, "l_elbow": -0.5}),
            (700, {}),
        ],
    },
    "demo_squat.d6a": {
        "description": "bend both legs into a shallow squat with level soles, hold, stand up",
        "frames": [
            (800, {f"{s}_{j}": v for s in "lr" for j, v in SQUAT.items()}),
            (600, {f"{s}_{j}": v for s in "lr" for j, v in SQUAT.items()}),
            (800, {}),
        ],
    },
}


def pulses_for(angles, cal, joint_of):
    """16 integer pulses (bus IDs 1-16) for a dict of joint angles; unspecified joints sit at the model zero."""
    out = []
    for sid in BODY_IDS:
        zero, sign, dpp = cal[sid]
        p = round(servo_map.rad_to_pulse(angles.get(joint_of[sid], 0.0), zero, sign, dpp))
        if not 0 <= p <= 1000:
            raise SystemExit(f"bus{sid} ({joint_of[sid]}): pulse {p} outside 0-1000")
        out.append(p)
    return out


def build(name):
    demo = DEMOS[name]
    cal = servo_map.calibration("reference", BODY_IDS)
    joint_of = {sid: r["joint"] for sid, r in servo_map.bus_channels().items()}
    known = set(joint_of.values())
    con = sqlite3.connect(":memory:")
    cols = ", ".join(f"Servo{i} INT" for i in BODY_IDS)
    con.execute(f"CREATE TABLE ActionGroup ([Index] INTEGER PRIMARY KEY, Time INT, {cols})")
    for index, (time_ms, angles) in enumerate(demo["frames"], start=1):
        unknown = set(angles) - known
        if unknown:
            raise SystemExit(f"{name}: unknown joints {sorted(unknown)}")
        con.execute(f"INSERT INTO ActionGroup VALUES ({', '.join('?' * (len(BODY_IDS) + 2))})",
                    [index, time_ms] + pulses_for(angles, cal, joint_of))
    con.commit()
    data = con.serialize()
    con.close()
    return bytes(data)


def manifest(blobs):
    files = []
    for name, data in blobs.items():
        demo = DEMOS[name]
        files.append({"path": name, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest(),
                      "frames": len(demo["frames"]), "duration_ms": sum(t for t, _ in demo["frames"]),
                      "servo_columns": BODY_IDS, "calibration": "reference",
                      "source": "synthetic: generated by tools/make_demo_action.py from joint-angle keyframes",
                      "description": demo["description"]})
    return {"status": "synthetic demonstration files, not robot recordings", "files": files}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    blobs = {name: build(name) for name in DEMOS}
    text = json.dumps(manifest(blobs), indent=2) + "\n"
    if a.check:
        for name, data in blobs.items():
            with open(os.path.join(DATA, name), "rb") as f:
                if f.read() != data:
                    raise SystemExit(f"{name} differs from generator output")
        with open(MANIFEST, encoding="utf-8") as f:
            if f.read() != text:
                raise SystemExit("MANIFEST.json differs from generator output")
        print(f"{len(blobs)} demo action groups and MANIFEST.json match the generator")
        return 0
    os.makedirs(DATA, exist_ok=True)
    for name, data in blobs.items():
        with open(os.path.join(DATA, name), "xb") as f:  # refuse to overwrite
            f.write(data)
    with open(MANIFEST, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {len(blobs)} demo action groups and MANIFEST.json to data/action-groups/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
