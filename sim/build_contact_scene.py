"""Build the floating-base, floor-contact TonyPi Pro scene from the checked fixed-base twin.

The fixed-base model and vendor files are never edited. This derived scene adds exactly what the vendor's own
scene.xml adds to its robot.xml (floor, light, sky, ground material, visual settings) plus a free root, and copies
the vendor's three free-root keyframes (home, prone, supine) verbatim. Robot self-contact stays ON as the vendor
designed it: primitive self-collision guards with explicit parent/child exclusions and a foot-to-foot pair.

Usage:
  .venv/bin/python -I sim/build_contact_scene.py           write build/tonypi_pro_contact_candidate.xml
  .venv/bin/python -I sim/build_contact_scene.py --check   verify the checked-in file equals the generator output
"""

import argparse
import copy
import hashlib
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "build/tonypi_pro_as_is.xml"
OUTPUT = ROOT / "build/tonypi_pro_contact_candidate.xml"
SOURCE_MANIFEST = ROOT / "SOURCE_MANIFEST.json"
VENDOR_DIR = ROOT / "vendor/tonypi/model"
COMMENT = re.compile(r"<!--.*?-->", re.S)


def verified(path: Path) -> bytes:
    """Bytes of a manifest-listed file, refusing if they differ from SOURCE_MANIFEST.json."""
    data = path.read_bytes()
    rel = path.relative_to(ROOT).as_posix()
    manifest = json.loads(SOURCE_MANIFEST.read_text(encoding="utf-8"))
    entry = next((item for item in manifest["files"] if item["path"] == rel), None)
    if entry is None:
        raise ValueError(f"{rel} is not in SOURCE_MANIFEST.json; run tools/make_manifest.py after building")
    if len(data) != entry["bytes"] or hashlib.sha256(data).hexdigest() != entry["sha256"]:
        raise ValueError(f"{rel} differs from SOURCE_MANIFEST.json; review provenance before deriving")
    return data


def vendor_xml(name: str) -> ET.Element:
    """A vendor XML file, checked against vendor/tonypi/SHA256SUMS, with comments removed in memory."""
    data = (VENDOR_DIR / name).read_bytes()
    sums = dict(reversed(line.split("  ", 1)) for line in
                (ROOT / "vendor/tonypi/SHA256SUMS").read_text(encoding="utf-8").splitlines() if line)
    if hashlib.sha256(data).hexdigest() != sums.get(f"model/{name}"):
        raise ValueError(f"vendor model/{name} differs from vendor/tonypi/SHA256SUMS")
    return ET.fromstring(COMMENT.sub("", data.decode("utf-8")))


def generate() -> bytes:
    root = ET.fromstring(verified(SOURCE))
    root.set("model", "tonypi_pro_contact_candidate")
    scene = vendor_xml("scene.xml")
    robot = vendor_xml("robot.xml")

    world = root.find("worldbody")
    torso = world.find("body[@name='torso']") if world is not None else None
    if torso is None or torso.find("freejoint") is not None or torso.find("joint") is not None:
        raise ValueError("expected one fixed torso body directly under worldbody")
    torso.insert(0, ET.Element("freejoint", {"name": "root"}))

    # Copy the vendor scene's additions, element by element, after the robot's own sections.
    for tag in ("statistic", "visual"):
        if root.find(tag) is not None:
            raise ValueError(f"baseline already has <{tag}>")
    anchor = list(root).index(root.find("option")) + 1
    for offset, tag in enumerate(("statistic", "visual")):
        root.insert(anchor + offset, copy.deepcopy(scene.find(tag)))
    asset = root.find("asset")
    for child in scene.find("asset"):
        asset.append(copy.deepcopy(child))
    for i, child in enumerate(scene.find("worldbody")):
        world.insert(i, copy.deepcopy(child))

    # The vendor's free-root keyframes fit this tree exactly (same joint order, free root first).
    keyframe = ET.SubElement(root, "keyframe")
    for key in robot.find("keyframe"):
        keyframe.append(copy.deepcopy(key))

    ET.indent(root, space="  ")
    return (ET.tostring(root, encoding="unicode") + "\n").encode("utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="compare regenerated bytes with the checked-in scene")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if OUTPUT.read_bytes() != generated:
            raise SystemExit("scene differs from generator output")
        print(f"scene matches generator: {OUTPUT.relative_to(ROOT).as_posix()}")
    else:
        OUTPUT.write_bytes(generated)
        print(f"wrote {OUTPUT.relative_to(ROOT).as_posix()} ({len(generated)} bytes)")


if __name__ == "__main__":
    main()
